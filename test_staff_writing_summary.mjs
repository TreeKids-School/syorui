import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const exports={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/staffWritingSummary.ts','utf8'),{compilerOptions:{module:1,target:9}}).outputText,{exports});
const counts={a:{nonIndividualCount:4},b:{nonIndividualCount:2},individualOnly:{nonIndividualCount:0},unassigned:{nonIndividualCount:3},formerStaff:{nonIndividualCount:1}};
const assigned={a:'A',b:'A',individualOnly:'B',formerStaff:'old',otherOfficeChild:'B'};
const before=JSON.stringify({counts,assigned});
const result=exports.summarizeStaffWritingDays(counts,assigned);
assert.equal(result.A.days,6);
assert.equal(result.A.childCount,2);
assert.equal(result.B,undefined);
assert.equal(result[''].days,3);
assert.equal(result.old.days,1);
assert.equal(Object.values(result).reduce((sum,row)=>sum+row.days,0),10);
assert.equal(JSON.stringify({counts,assigned}),before);
const cleared=exports.summarizeStaffWritingDays(counts,{});
assert.equal(cleared[''].days,10);
assert.equal(cleared[''].childCount,4);
