import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
function load(path){const exports={};vm.runInNewContext(ts.transpileModule(fs.readFileSync(path,'utf8'),{compilerOptions:{module:1,target:9}}).outputText,{exports});return exports;}
const {createLatestSaveQueue,mergeSavedSupportIds,supportDraftSignature}=load('src/lib/supportSaveQueue.ts');
let release,start;
const gate=new Promise(resolve=>release=resolve);
const started=new Promise(resolve=>start=resolve);
const queue=createLatestSaveQueue();
const writes=[];let inFlight=0,max=0;
const task=(text,delay)=>async()=>{inFlight++;max=Math.max(max,inFlight);writes.push(text);if(delay){start();await gate;}inFlight--;};
const first=queue.run(task('古い入力',true));
await started;
queue.run(task('途中の入力',false));
const final=queue.run(task('最新の入力',false));
release();await Promise.all([first,final]);
assert.deepEqual(writes,['古い入力','最新の入力']);assert.equal(max,1);
const saved=new Map([['row-a','id-a'],['row-b','id-b'],['deleted','id-deleted']]);
const live=[{localKey:'row-b',date:'10月8日',content:{resultInfo:'保存中に入力した最新の結果',futurePlan:'最新の予定',supportContent:['①','③']}},{localKey:'row-a',date:'10月12日',content:{resultInfo:'日付も編集',futurePlan:'追加した予定',supportContent:['②']}}];
const before=JSON.stringify(live);
const merged=mergeSavedSupportIds(live,saved);
assert.equal(merged[0].id,'id-b');assert.equal(merged[1].id,'id-a');
assert.equal(merged.length,2);assert.equal(merged[0].content,live[0].content);assert.equal(merged[1].date,'10月12日');
assert.equal(JSON.stringify(live),before);
assert.equal(mergeSavedSupportIds(merged,saved),merged);
assert.equal(supportDraftSignature({goals:'目標'},live),supportDraftSignature({goals:'目標'},merged));
assert.notEqual(supportDraftSignature({goals:'目標'},live),supportDraftSignature({goals:'変更'},live));
assert.notEqual(supportDraftSignature({},live),supportDraftSignature({},[{...live[0],content:{resultInfo:'さらに入力'}}]));
await assert.rejects(queue.run(async()=>{throw Error('保存失敗');}),/保存失敗/);
await queue.run(task('再試行',false));assert.equal(writes.at(-1),'再試行');
const {isArchivedChild}=load('src/lib/childArchive.ts');
for(const data of [{archived:true},{isArchived:true},{status:'archived'},{status:' ARCHIVED '}])assert.equal(isArchivedChild(data),true);
for(const data of [{},{archived:false},{isArchived:false},{status:'active'},{archived:'false'}])assert.equal(isArchivedChild(data),false);
const children=[{id:'active',archived:isArchivedChild({status:'active'})},{id:'old',archived:isArchivedChild({isArchived:true})}];
assert.deepEqual(children.filter(child=>!child.archived).map(child=>child.id),['active']);
console.log('PASS: 保存遅延中の最新入力/ボタン選択/日付変更を維持、IDだけ反映、削除行を復活させない、保存を直列化して最新要求に集約、失敗後再試行、ID追加で重複保存しない');
console.log('PASS: 児童アーカイブの3形式を正規化、通常児童を保持しアーカイブ児童だけ表から除外');

